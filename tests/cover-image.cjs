const assert = require('node:assert/strict');
const fs = require('node:fs');
const Module = require('node:module');
const path = require('node:path');
const file = path.resolve(__dirname, '../api/admin.js');
const mod = new Module(file, module);
mod.filename = file; mod.paths = module.paths;
mod._compile(fs.readFileSync(file, 'utf8') + '\nmodule.exports={normalize,representativeImage,article};', file);
const api = mod.exports;
const base = structuredClone(require('../content/admin-cases.json')[0]);
const png = Buffer.alloc(24);
Buffer.from('89504e470d0a1a0a', 'hex').copy(png);
png.writeUInt32BE(1200, 16); png.writeUInt32BE(1200, 20);
const thumbnailImage = {data: png.toString('base64')};
const webp = Buffer.from('RIFF0000WEBPfixture');
const coverImage = {data:webp.toString('base64'),width:1200,height:1600};
const input = {...base, thumbnailImage, representativeMode:undefined};
const without = api.normalize({...input}, []);
assert.equal(without.representativeMode, 'generated');
assert.equal(api.representativeImage(without), without.thumbnail);
const withCover = api.normalize({...input, coverImage}, []);
assert.equal(withCover.representativeMode, 'cover');
assert.equal(api.representativeImage(withCover).name, 'representative-cover.webp');
const html = api.article(withCover);
assert.ok(html.includes('representative-cover.webp'));
assert.ok(!html.split('<body')[1].includes('representative-cover.webp'), 'cover must not appear in body');
assert.ok(html.includes(withCover.photos[0].name));
assert.ok(html.includes(withCover.photos[1].name));
const existing = {...withCover, coverImage:undefined, thumbnailImage:undefined};
const edit = api.normalize({...input, originalPath:existing.path, representativeMode:'cover'}, [existing]);
assert.deepEqual(edit.cover, existing.cover);
const removed = api.normalize({...input, originalPath:existing.path, representativeMode:'cover',removeCover:true}, [existing]);
assert.equal(removed.cover, undefined);
assert.equal(removed.representativeMode,'generated');
assert.throws(()=>api.normalize({...input,coverImage:{...coverImage,data:'invalid'}},[]),/문구형/);
for (const mode of ['photo1','photo2','generated']) {
  const c=api.normalize({...input,representativeMode:mode},[]);
  assert.equal(c.representativeMode,mode);
}
console.log('PASS: optional cover, fallback, edit preservation, removal, legacy choices, validation and body/SEO separation');
